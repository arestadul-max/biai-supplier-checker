"""
Command-line interface for the supplier document checker.

Usage:
    python cli.py \\
        --pdfs data/*.pdf \\
        --pr   data/purchase-request.csv \\
        --rules data/company-rules.md   # displayed only; not parsed
        [--interactive]                 # prompt a person to resolve NEEDS_PERSON cases

Writes outputs/report.md and outputs/results.json.
"""

import argparse
import json
import os
import sys
from datetime import datetime
from pathlib import Path

# Force UTF-8 on Windows terminals that default to cp1252
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")

# Add project root to path so `src` is importable
sys.path.insert(0, str(Path(__file__).parent))

from src.models import APPROVE, REJECT, NEEDS_PERSON, VALID_DECISIONS
from src.pipeline import load_config, load_pr_items, run_batch


OUTPUTS_DIR = Path(__file__).parent / "outputs"

DECISION_LABEL = {
    APPROVE:      "[APPROVE]",
    REJECT:       "[REJECT]",
    NEEDS_PERSON: "[NEEDS A PERSON]",
}


def _parse_args():
    p = argparse.ArgumentParser(description="Check supplier quotation PDFs against company rules.")
    p.add_argument("--pdfs",  nargs="+", required=True, help="Supplier PDF files to check")
    p.add_argument("--pr",    required=True,             help="Purchase-request CSV file")
    p.add_argument("--rules", required=False,            help="Company-rules .md file (displayed only)")
    p.add_argument("--config", default=None,             help="Path to rules_config.json (optional)")
    p.add_argument("--interactive", action="store_true", help="Prompt human to resolve NEEDS_PERSON cases")
    p.add_argument("--output-dir", default=str(OUTPUTS_DIR), help="Directory for report.md and results.json")
    return p.parse_args()


def _print_result(r, idx: int, total: int) -> None:
    label = DECISION_LABEL.get(r.decision, r.decision)
    print(f"\n[{idx}/{total}] {r.pdf_filename}")
    print(f"  Supplier : {r.supplier_name}")
    print(f"  Item     : {r.item_letter}")
    print(f"  Decision : {label}")
    for reason in r.reasons:
        print(f"  Reason   : {reason}")
    for ev in r.evidence:
        if ev:
            print(f"  Evidence : \"{ev}\"")
    if r.error:
        print(f"  Error    : {r.error}")


def _interactive_review(results, pr_items):
    """
    Ask a human to approve or reject each NEEDS_PERSON case.
    Saves their name and reason in the result.
    """
    needs = [r for r in results if r.decision == NEEDS_PERSON]
    if not needs:
        print("\nNo documents need human review.")
        return

    print(f"\n{'='*60}")
    print(f"HUMAN REVIEW — {len(needs)} document(s) need your decision")
    print(f"{'='*60}")

    for r in needs:
        print(f"\nDocument : {r.pdf_filename}")
        print(f"Supplier : {r.supplier_name}  |  Item: {r.item_letter}")
        for reason in r.reasons:
            print(f"Issue    : {reason}")
        for ev in r.evidence:
            if ev:
                print(f"Evidence : \"{ev}\"")

        while True:
            choice = input("  Your decision [A=Approve / R=Reject / S=Skip]: ").strip().upper()
            if choice in ("A", "R", "S"):
                break
            print("  Please enter A, R, or S.")

        if choice == "S":
            print("  Skipped.")
            continue

        name   = input("  Your name: ").strip() or "Anonymous"
        reason = input("  Reason for your decision: ").strip() or "(no reason given)"

        r.human_override = APPROVE if choice == "A" else REJECT
        r.human_name     = name
        r.human_reason   = reason
        print(f"  Saved: {r.human_override} by {name}")


def _write_report(results, output_dir: Path, rules_path: str = None) -> None:
    """Write a Markdown report to output_dir/report.md."""
    output_dir.mkdir(parents=True, exist_ok=True)
    report_path = output_dir / "report.md"

    approve_count = sum(1 for r in results if r.decision == APPROVE)
    reject_count  = sum(1 for r in results if r.decision == REJECT)
    review_count  = sum(1 for r in results if r.decision == NEEDS_PERSON)

    with open(report_path, "w", encoding="utf-8") as f:
        f.write(f"# Supplier Document Check — {datetime.now():%Y-%m-%d %H:%M}\n\n")
        f.write(f"> **HONESTY NOTE:** This report was generated by an AI system (built with Claude). "
                f"The answer key is the AI's own reading of the rules — BIAI provided no official answers.\n\n")
        if rules_path:
            f.write(f"> Rules file shown for reference: `{rules_path}`. "
                    f"Thresholds applied from `rules_config.json`.\n\n")
        f.write(f"## Summary\n\n")
        f.write(f"| Decision | Count |\n|---|---|\n")
        f.write(f"| ✅ Approve | {approve_count} |\n")
        f.write(f"| ❌ Reject  | {reject_count}  |\n")
        f.write(f"| ⚠️  Needs a person | {review_count} |\n")
        f.write(f"| **Total** | **{len(results)}** |\n\n")

        f.write("## Results\n\n")
        for r in results:
            f.write(f"### {r.pdf_filename}\n\n")
            f.write(f"- **Supplier**: {r.supplier_name}\n")
            f.write(f"- **Item**: {r.item_letter}\n")
            f.write(f"- **Decision**: {r.decision}\n")
            f.write(f"- **Reasons**:\n")
            for reason in r.reasons:
                f.write(f"  - {reason}\n")
            if r.evidence:
                f.write(f"- **Evidence** (verbatim from document):\n")
                for ev in r.evidence:
                    if ev:
                        f.write(f'  - "{ev}"\n')
            if r.human_override:
                f.write(f"- **Human override**: {r.human_override} "
                        f"(by {r.human_name}): {r.human_reason}\n")
            if r.error:
                f.write(f"- **Error**: {r.error}\n")
            f.write("\n")

    print(f"\nReport written to: {report_path}")
    return report_path


def _write_json(results, output_dir: Path) -> None:
    """Write machine-readable results to output_dir/results.json."""
    output_dir.mkdir(parents=True, exist_ok=True)
    json_path = output_dir / "results.json"

    data = []
    for r in results:
        data.append({
            "file":            r.pdf_filename,
            "supplier":        r.supplier_name,
            "item":            r.item_letter,
            "decision":        r.decision,
            "reasons":         r.reasons,
            "evidence":        [e for e in r.evidence if e],
            "human_override":  r.human_override,
            "human_name":      r.human_name,
            "human_reason":    r.human_reason,
            "error":           r.error,
            "rule_results": [
                {
                    "rule_id":   rr.rule_id,
                    "severity":  rr.severity,
                    "triggered": rr.triggered,
                    "reason":    rr.reason,
                    "evidence":  rr.evidence,
                }
                for rr in r.rule_results
            ],
        })

    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)

    print(f"JSON written to: {json_path}")
    return json_path


def main():
    args = _parse_args()
    output_dir = Path(args.output_dir)

    print("Supplier Document Checker — BIAI Round 2 Task 1")
    print("=" * 50)
    print("HONESTY: This system was built with AI (Claude). Decisions are by deterministic Python rules.")
    print()

    # Load config and purchase request
    try:
        config   = load_config(args.config)
        pr_items = load_pr_items(args.pr)
        print(f"Purchase request loaded: {len(pr_items)} items ({', '.join(sorted(pr_items))})")
    except Exception as exc:
        print(f"ERROR: Could not load purchase request or config: {exc}")
        sys.exit(1)

    # Run the pipeline on all PDFs
    print(f"Processing {len(args.pdfs)} PDF file(s)...\n")
    results = run_batch(args.pdfs, pr_items, config)

    # Print results to console
    for i, r in enumerate(results, 1):
        _print_result(r, i, len(results))

    # Optional interactive review
    if args.interactive:
        _interactive_review(results, pr_items)

    # Write outputs
    _write_report(results, output_dir, args.rules)
    _write_json(results, output_dir)

    # Print summary
    approve = sum(1 for r in results if r.decision == APPROVE)
    reject  = sum(1 for r in results if r.decision == REJECT)
    review  = sum(1 for r in results if r.decision == NEEDS_PERSON)
    print(f"\nDone. {approve} Approve | {reject} Reject | {review} Needs a person")

    # Validate Rule 2: every result must have a non-empty reason and a valid decision
    for r in results:
        assert r.decision in VALID_DECISIONS, f"BUG: invalid decision for {r.pdf_filename}"
        assert r.reasons, f"BUG: no reasons for {r.pdf_filename}"


if __name__ == "__main__":
    main()
